"use client";

import * as React from "react";
import { Star, Zap } from "lucide-react";
import {
  OUTPUT_SORT_OPTIONS,
  OUTPUT_TYPE_OPTIONS,
  SEED_OUTPUTS,
  type OutputSort,
  type OutputTypeFilter,
  type TaskOutput,
} from "@/components/planning/data";
import { OutputCard } from "@/components/planning/output-card";
import { OutputPreview } from "@/components/planning/output-preview";
import {
  PlanningEmptyState,
  PlanningSearchField,
  PlanningSelect,
} from "@/components/planning/planning-controls";
import {
  PlanningSection,
  PlanningSectionBadge,
} from "@/components/planning/planning-section";
import { cn } from "@/lib/utils";

function matchesQuery(output: TaskOutput, query: string) {
  return [output.name, output.task, output.preview, ...output.tags].some(
    (field) => field.toLowerCase().includes(query),
  );
}

function sortOutputs(outputs: TaskOutput[], sort: OutputSort) {
  const key = sort === "edited" ? "lastModified" : "createdAt";
  const direction = sort === "oldest" ? 1 : -1;

  return [...outputs].sort(
    (a, b) =>
      direction * (new Date(b[key]).getTime() - new Date(a[key]).getTime()),
  );
}

export function OutputsSection({
  onNotify,
}: {
  onNotify: (title: string, description?: string) => void;
}) {
  const [outputs, setOutputs] = React.useState<TaskOutput[]>(SEED_OUTPUTS);
  const [query, setQuery] = React.useState("");
  const [typeFilter, setTypeFilter] = React.useState<OutputTypeFilter>("all");
  const [sort, setSort] = React.useState<OutputSort>("newest");
  const [favoritesOnly, setFavoritesOnly] = React.useState(false);
  const [previewId, setPreviewId] = React.useState<string | null>(null);

  const normalisedQuery = query.trim().toLowerCase();

  const visible = sortOutputs(
    outputs.filter((output) => {
      if (favoritesOnly && !output.favorite) {
        return false;
      }

      if (typeFilter !== "all" && output.type !== typeFilter) {
        return false;
      }

      return !normalisedQuery || matchesQuery(output, normalisedQuery);
    }),
    sort,
  );

  const preview = outputs.find((output) => output.id === previewId) ?? null;

  function toggleFavorite(id: string) {
    setOutputs((current) =>
      current.map((output) =>
        output.id === id ? { ...output, favorite: !output.favorite } : output,
      ),
    );
  }

  function duplicateOutput(output: TaskOutput) {
    const copy: TaskOutput = {
      ...output,
      createdAt: new Date().toISOString(),
      favorite: false,
      id: `${output.id}-copy-${Date.now()}`,
      lastModified: new Date().toISOString(),
      name: `${output.name} (copy)`,
      status: "draft",
    };

    setOutputs((current) => [copy, ...current]);
    setPreviewId(null);
    onNotify("Duplicated", `${output.name} was copied to your library.`);
  }

  function downloadOutput(output: TaskOutput) {
    setPreviewId(null);
    onNotify("Preparing download", `${output.name} will download shortly.`);
  }

  function editOutput(output: TaskOutput) {
    setPreviewId(null);
    onNotify("Editing coming soon", `${output.name} opens in the editor soon.`);
  }

  return (
    <PlanningSection
      action={<PlanningSectionBadge>{outputs.length}</PlanningSectionBadge>}
      description="Your personal knowledge library. Every artifact generated by your tasks lives here - edit, duplicate, download, or export."
      title="Saved task outputs"
    >
      <div className="mb-5 flex flex-wrap items-center gap-3">
        <PlanningSearchField
          label="Search library"
          onChange={setQuery}
          placeholder="Search library..."
          value={query}
        />
        <div className="flex items-center gap-2">
          <PlanningSelect
            label="Filter by type"
            onChange={setTypeFilter}
            options={OUTPUT_TYPE_OPTIONS}
            value={typeFilter}
          />
          <PlanningSelect
            label="Sort outputs"
            onChange={setSort}
            options={OUTPUT_SORT_OPTIONS}
            value={sort}
          />
          <button
            aria-label="Show favourites only"
            aria-pressed={favoritesOnly}
            className={cn(
              "flex size-8 items-center justify-center rounded-full border transition-colors duration-200 ease-contentual",
              favoritesOnly
                ? "border-foreground bg-accent text-accent-foreground"
                : "border-border bg-background text-muted hover:border-foreground hover:text-foreground",
            )}
            onClick={() => setFavoritesOnly((current) => !current)}
            type="button"
          >
            <Star className={cn("size-4", favoritesOnly && "fill-current")} />
          </button>
        </div>
      </div>

      {outputs.length === 0 ? (
        <PlanningEmptyState
          description="Generated outputs automatically appear here after you complete tasks. Start your first task to see your work."
          icon={<Zap className="size-6" />}
          title="Your library is empty"
        />
      ) : visible.length === 0 ? (
        <PlanningEmptyState
          compact
          description="Try adjusting your search or filters to find what you're looking for."
          title="No matching outputs"
        />
      ) : (
        <div className="grid grid-cols-[repeat(auto-fill,minmax(300px,1fr))] gap-4">
          {visible.map((output) => (
            <OutputCard
              key={output.id}
              onDownload={downloadOutput}
              onToggleFavorite={toggleFavorite}
              onView={(selected) => setPreviewId(selected.id)}
              output={output}
            />
          ))}
        </div>
      )}

      {preview ? (
        <OutputPreview
          onClose={() => setPreviewId(null)}
          onDownload={downloadOutput}
          onDuplicate={duplicateOutput}
          onEdit={editOutput}
          output={preview}
        />
      ) : null}
    </PlanningSection>
  );
}
